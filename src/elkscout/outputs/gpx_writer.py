"""GPX output (the OnX deliverable).

write_gpx_files(ws, cfg) writes one GPX with every waypoint plus one per hunt
area, then hard-verifies each file: within OnX's import limits
(<= gpx_max_waypoints markups, <= gpx_max_bytes), re-parses with gpxpy to the
same count, names ASCII and <= 32 chars, descriptions <= desc_max_chars.
Symbols are Garmin-standard names OnX tolerates. Output is deterministic
(no timestamps).
"""

from __future__ import annotations

import logging
from pathlib import Path

import gpxpy.gpx

from ..config import Config
from ..paths import Workspace

log = logging.getLogger("elkscout.gpx")

SYMBOLS = {
    "BED": "Flag, Blue",
    "FEED": "Flag, Green",
    "WATER": "Drinking Water",
    "SADDLE": "Flag, Red",
    "GLASS": "Binoculars",
    "CAMP": "Campground",
    "ACCESS": "Parking Area",
}

MAX_NAME_CHARS = 32
FT_TO_M = 1.0 / 3.28084


def write_gpx_files(ws: Workspace, cfg: Config) -> list[Path]:
    from ..waypoints import load_waypoints  # deferred: avoid outputs<->waypoints import cycle

    wp, _areas = load_waypoints(ws)
    paths: list[Path] = []

    all_path = ws.gpx_all(cfg.unit)
    _write_one(all_path, wp, cfg, title=f"ElkScout Unit {cfg.unit}")
    paths.append(all_path)

    for slug in sorted(wp["area_slug"].unique()):
        sub = wp[wp["area_slug"] == slug]
        area_path = ws.gpx_area(cfg.unit, slug)
        _write_one(area_path, sub, cfg, title=f"ElkScout Unit {cfg.unit} - {sub.iloc[0]['hunt_area']}")
        paths.append(area_path)

    log.info("gpx: wrote %d file(s), %d waypoints total", len(paths), len(wp))
    return paths


def _write_one(path: Path, wp, cfg: Config, title: str) -> None:
    gpx = gpxpy.gpx.GPX()
    gpx.name = title
    gpx.description = (
        f"Generated by ElkScout ({cfg.profile}) from public GIS data "
        "(USGS 3DEP, NHD, NLCD, MTBS, BLM SMA, OSM, SNOTEL). "
        "Verify land status and current IDFG rules before hunting."
    )
    gpx.creator = "elkscout"

    for _, row in wp.iterrows():
        _validate_row(row, cfg)
        w = gpxpy.gpx.GPXWaypoint(
            latitude=round(float(row.geometry.y), 6),
            longitude=round(float(row.geometry.x), 6),
            elevation=round(float(row["elevation_ft"]) * FT_TO_M, 1),
        )
        w.name = row["name"]
        w.description = row["desc"]
        w.symbol = SYMBOLS[row["wp_type"]]
        gpx.waypoints.append(w)

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(gpx.to_xml(version="1.1"), encoding="utf-8")
    _verify(path, expected=len(wp), cfg=cfg)


def _validate_row(row, cfg: Config) -> None:
    name = str(row["name"])
    if not name.isascii() or len(name) > MAX_NAME_CHARS:
        raise ValueError(f"waypoint name not OnX-safe (ASCII, <= {MAX_NAME_CHARS} chars): {name!r}")
    desc = str(row["desc"])
    if len(desc) > cfg.outputs.desc_max_chars:
        raise ValueError(f"description exceeds {cfg.outputs.desc_max_chars} chars for {name!r}")
    lat, lon = float(row.geometry.y), float(row.geometry.x)
    if not (-90 <= lat <= 90 and -180 <= lon <= 180):
        raise ValueError(f"bad coordinates for {name!r}: {lat}, {lon}")
    if row["wp_type"] not in SYMBOLS:
        raise ValueError(f"unknown waypoint type {row['wp_type']!r} for {name!r}")


def _verify(path: Path, expected: int, cfg: Config) -> None:
    if expected > cfg.outputs.gpx_max_waypoints:
        raise ValueError(f"{path.name}: {expected} waypoints exceeds OnX limit {cfg.outputs.gpx_max_waypoints}")
    size = path.stat().st_size
    if size > cfg.outputs.gpx_max_bytes:
        raise ValueError(f"{path.name}: {size} bytes exceeds OnX limit {cfg.outputs.gpx_max_bytes}")
    with open(path, encoding="utf-8") as fh:
        parsed = gpxpy.parse(fh)
    if len(parsed.waypoints) != expected:
        raise ValueError(f"{path.name}: re-parse found {len(parsed.waypoints)} waypoints, expected {expected}")
